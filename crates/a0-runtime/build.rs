//! Compiles the C runtime into a static library.
//!
//! The library is linked into Rust users of this crate (the interpreter calls it directly) and a copy
//! is kept in `OUT_DIR/a0rt.embedded` so the native backend can hand it to the system linker.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

fn main() {
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let ffi = out.join("ffi_call.c");
    if env::var("CARGO_CFG_TARGET_ARCH").as_deref() == Ok("wasm32") {
        let (source, header) = generate_wasm_wrappers(&manifest);
        fs::write(&ffi, source).unwrap();
        fs::write(out.join("ffi_wrappers.h"), header).unwrap();
    } else {
        fs::write(&ffi, generate_ffi_call()).unwrap();
    }

    cc::Build::new()
        .include(manifest.join("include"))
        .include(&out)
        .file(manifest.join("c/rt.c"))
        .file(manifest.join("c/gc.c"))
        .file(manifest.join("c/string.c"))
        .file(manifest.join("c/array.c"))
        .file(manifest.join("c/map.c"))
        .file(manifest.join("c/any.c"))
        .file(manifest.join("c/trace.c"))
        .file(manifest.join("c/std.c"))
        .file(manifest.join("c/symbols.c"))
        .file(&ffi)
        .warnings(true)
        .compile("a0rt");

    let lib = ["a0rt.lib", "liba0rt.a"]
        .iter()
        .map(|name| out.join(name))
        .find(|path| path.exists())
        .expect("cc did not produce the a0rt static library");
    fs::copy(&lib, out.join("a0rt.embedded")).unwrap();

    // Dependents (language runtimes) find the header through DEP_A0RT_INCLUDE.
    println!("cargo:include={}", manifest.join("include").display());
    println!("cargo:rerun-if-changed=c");
    println!("cargo:rerun-if-changed=include");
    println!("cargo:rerun-if-changed=build.rs");
}

/// Generates `a0_ffi_call`: one case per call shape (up to 8 arguments, each an integer slot or a
/// double, returning nothing, an integer or a double). The C compiler does the ABI work.
fn generate_ffi_call() -> String {
    const MAX_ARGS: u32 = 8;
    let mut c = String::new();
    c.push_str("/* Generated by a0-runtime/build.rs. Do not edit. */\n");
    c.push_str("#include \"a0rt.h\"\n#include <string.h>\n\n");
    c.push_str("typedef uint64_t I;\ntypedef double F;\n\n");
    c.push_str(
        "int32_t a0_ffi_call(void *fn, int32_t nargs, const uint64_t *a, uint32_t fm,\n\
         \x20                   int32_t rk, uint64_t *ret) {\n",
    );
    let _ = writeln!(
        c,
        "    if (nargs < 0 || nargs > {MAX_ARGS} || (fm >> nargs) != 0 || rk < 0 || rk > 2) return -1;"
    );
    let _ = writeln!(c, "    F f[{MAX_ARGS}];");
    let _ = writeln!(c, "    for (int i = 0; i < {MAX_ARGS}; i++) {{");
    c.push_str("        if (i < nargs) memcpy(&f[i], &a[i], sizeof(F)); else f[i] = 0;\n    }\n");
    c.push_str("    switch ((nargs << 10) | (int32_t)(fm << 2) | rk) {\n");
    for n in 0..=MAX_ARGS {
        for mask in 0..(1u32 << n) {
            let types: Vec<&str> = (0..n)
                .map(|i| if mask & (1 << i) != 0 { "F" } else { "I" })
                .collect();
            let params = if n == 0 {
                "void".to_string()
            } else {
                types.join(", ")
            };
            let args: Vec<String> = (0..n)
                .map(|i| {
                    if mask & (1 << i) != 0 {
                        format!("f[{i}]")
                    } else {
                        format!("a[{i}]")
                    }
                })
                .collect();
            let args = args.join(", ");
            for rk in 0..3u32 {
                let key = (n << 10) | (mask << 2) | rk;
                let call = match rk {
                    0 => format!("((void (*)({params}))fn)({args});"),
                    1 => format!("*ret = ((I (*)({params}))fn)({args});"),
                    _ => format!(
                        "{{ F r = ((F (*)({params}))fn)({args}); memcpy(ret, &r, sizeof r); }}"
                    ),
                };
                let _ = writeln!(c, "    case {key}: {call} return 0;");
            }
        }
    }
    c.push_str("    }\n    return -1;\n}\n");
    c
}

