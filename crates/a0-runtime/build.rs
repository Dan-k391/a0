/// For wasm32, where calling a function through a pointer of another type traps (the interpreter
/// passes every argument as a 64-bit word): a wrapper `uint64_t a0_w_<name>(const uint64_t *args)`
/// for each function of the symbol table, which converts the words to the function's parameter
/// types and its result back, and an `a0_ffi_call` that calls wrappers. `symbols.c` puts the
/// wrappers in the table. Returns the C file and the header declaring the wrappers.
fn generate_wasm_wrappers(manifest: &std::path::Path) -> (String, String) {
    let header = fs::read_to_string(manifest.join("include/a0rt.h")).unwrap();
    let header = strip_comments(&header);
    let symbols = fs::read_to_string(manifest.join("c/symbols.c")).unwrap();
    let table = &symbols[symbols.find("a0_rt_symbols[]").expect("the symbol table")..];
    let table = &table[..table
        .find("{NULL, NULL}")
        .expect("the end of the symbol table")];
    let names: Vec<&str> = table
        .match_indices("SYM(")
        .filter_map(|(i, _)| {
            let rest = &table[i + 4..];
            Some(&rest[..rest.find(')')?])
        })
        .collect();
    let mut c = String::from(
        "/* Generated by a0-runtime/build.rs for wasm32. Do not edit. */\n\
         #include \"a0rt.h\"\n#include <math.h>\n#include <stdio.h>\n#include <stdlib.h>\n\
         #include <string.h>\n\n\
         static double a0_w_f(uint64_t w) { double d; memcpy(&d, &w, sizeof d); return d; }\n\
         static uint64_t a0_w_bits(double d) { uint64_t w; memcpy(&w, &d, sizeof w); return w; }\n\n",
    );
    let mut h = String::from("/* Generated by a0-runtime/build.rs for wasm32. Do not edit. */\n");
    for name in names {
        let (ret, params) = prototype(&header, name)
            .or_else(|| C_LIBRARY.iter().find_map(|p| prototype(p, name)))
            .unwrap_or_else(|| panic!("no prototype for `{name}` in a0rt.h or C_LIBRARY"));
        let args: Vec<String> = params
            .iter()
            .enumerate()
            .map(|(i, t)| match t.as_str() {
                "double" => format!("a0_w_f(a[{i}])"),
                t if t.contains('*') => format!("({t})(uintptr_t)a[{i}]"),
                t => format!("({t})a[{i}]"),
            })
            .collect();
        let call = format!("{name}({})", args.join(", "));
        let body = match ret.as_str() {
            "void" => format!("{call}; return 0;"),
            "double" => format!("return a0_w_bits({call});"),
            t if t.contains('*') => format!("return (uint64_t)(uintptr_t){call};"),
            t if t.starts_with('u') || t == "size_t" => format!("return (uint64_t){call};"),
            _ => format!("return (uint64_t)(int64_t){call};"),
        };
        let unused = if params.is_empty() { " (void)a;" } else { "" };
        let _ = writeln!(
            c,
            "uint64_t a0_w_{name}(const uint64_t *a) {{{unused} {body} }}"
        );
        let _ = writeln!(h, "uint64_t a0_w_{name}(const uint64_t *a);");
    }
    c.push_str(
        "\nint32_t a0_ffi_call(void *fn, int32_t nargs, const uint64_t *a, uint32_t fm,\n\
         \x20                   int32_t rk, uint64_t *ret) {\n\
         \x20   (void)nargs;\n    (void)fm;\n\
         \x20   uint64_t r = ((uint64_t (*)(const uint64_t *))fn)(a);\n\
         \x20   if (rk != 0) *ret = r;\n    return 0;\n}\n",
    );
    (c, h)
}

fn strip_comments(text: &str) -> String {
    let mut out = String::new();
    let mut rest = text;
    while let Some(i) = rest.find("/*") {
        out.push_str(&rest[..i]);
        rest = rest[i..].find("*/").map_or("", |j| &rest[i + j + 2..]);
    }
    out.push_str(rest);
    out
}

/// The result type and parameter types of the declaration of `name` in `text`.
fn prototype(text: &str, name: &str) -> Option<(String, Vec<String>)> {
    let mut search = 0;
    while let Some(i) = text[search..].find(name) {
        let at = search + i;
        search = at + name.len();
        let before = text[..at].chars().next_back();
        if before.is_some_and(|c| c.is_ascii_alphanumeric() || c == '_') {
            continue;
        }
        let after = text[search..].trim_start();
        let Some(params) = after.strip_prefix('(') else {
            continue;
        };
        let close = params.find(')')?;
        let start = text[..at].rfind([';', '}', '\n', '{']).map_or(0, |p| p + 1);
        let ret = text[start..at]
            .replace("A0_NORETURN", "")
            .replace("extern", "")
            .trim()
            .to_string();
        if ret.is_empty() || ret.starts_with('#') {
            continue;
        }
        let params: Vec<String> = params[..close]
            .split(',')
            .map(|p| param_type(p.trim()))
            .filter(|p| !p.is_empty() && p != "void")
            .collect();
        return Some((ret, params));
    }
    None
}

/// `const char *s` is `const char *`; a type alone (`size_t`) stays as it is.
fn param_type(p: &str) -> String {
    let tokens: Vec<&str> = p.split_whitespace().collect();
    let last = tokens.last().copied().unwrap_or("");
    let named = last.trim_start_matches('*');
    let is_type_word = |w: &str| {
        matches!(
            w,
            "int" | "char" | "double" | "float" | "void" | "long" | "short" | "unsigned" | "signed"
        ) || w.ends_with("_t")
            || w.starts_with("A0")
    };
    if tokens.len() > 1 && !named.is_empty() && !is_type_word(named) {
        let stars = last.len() - named.len();
        let mut t = tokens[..tokens.len() - 1].join(" ");
        if stars > 0 {
            t.push(' ');
            t.push_str(&"*".repeat(stars));
        }
        t
    } else {
        p.to_string()
    }
}
